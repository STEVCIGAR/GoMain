package main

import (
	"fmt"
)

func main() {
	var (
		defaultInt     int
		defaultUint    uint
		defaultFloat   float32
		defaultBoolean bool
		defaultText    string
	)

	fmt.Println("Default Int:", defaultInt)
	fmt.Println("Default Uint:", defaultUint)
	fmt.Println("Default Float:", defaultFloat)
	fmt.Println("Default Boolean:", defaultBoolean)
	fmt.Println("Default Text:", defaultText)
}
